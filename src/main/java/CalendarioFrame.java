private void carregarTarefasDoBanco() {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblCalendario.getModel();

    modelo.setRowCount(0);

    String sql = "SELECT id_tarefa, prazo, titulo, descricao "
               + "FROM tarefas ORDER BY prazo";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
        java.sql.ResultSet rs = stmt.executeQuery()
    ) {
        while (rs.next()) {
            int idTarefa = rs.getInt("id_tarefa");

            java.sql.Date prazoBanco = rs.getDate("prazo");

            String data = prazoBanco == null
                    ? ""
                    : new java.text.SimpleDateFormat("dd/MM/yyyy")
                            .format(prazoBanco);

            modelo.addRow(new Object[]{
                idTarefa,
                data,
                rs.getString("titulo"),
                rs.getString("descricao")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar tarefas do calendário: " + e.getMessage(),
                "Erro de banco de dados",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
