    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
       String data = txtData.getText().trim();
    String titulo = txtTitulo.getText().trim();
    String descricao = txtDescricao.getText().trim();

    if (data.isEmpty() || titulo.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe a data e o título da tarefa."
        );
        return;
    }

    java.sql.Date prazoSQL;

    try {
        java.text.SimpleDateFormat formato =
                new java.text.SimpleDateFormat("dd/MM/yyyy");

        formato.setLenient(false);

        java.util.Date dataConvertida = formato.parse(data);
        prazoSQL = new java.sql.Date(dataConvertida.getTime());

    } catch (java.text.ParseException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Data inválida. Digite no formato dd/MM/aaaa.\n"
                + "Exemplo: 25/10/2026"
        );
        return;
    }

    String sql;

    if (modoEdicao && linhaEdicao != -1) {
        sql = "UPDATE tarefas "
                + "SET prazo = ?, titulo = ?, descricao = ? "
                + "WHERE id_tarefa = ?";
    } else {
        sql = "INSERT INTO tarefas "
                + "(titulo, descricao, status, id_usuario, prioridade, prazo) "
                + "VALUES (?, ?, ?, ?, ?, ?)";
    }

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql)
    ) {
        if (modoEdicao && linhaEdicao != -1) {
            int idTarefa = Integer.parseInt(
                    tblCalendario.getValueAt(linhaEdicao, 0).toString()
            );

            stmt.setDate(1, prazoSQL);
            stmt.setString(2, titulo);
            stmt.setString(3, descricao);
            stmt.setInt(4, idTarefa);

            int linhasAfetadas = stmt.executeUpdate();

            if (linhasAfetadas == 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Nenhuma tarefa foi atualizada. Verifique se ela ainda existe."
                );
                return;
            }

        } else {
            stmt.setString(1, titulo);
            stmt.setString(2, descricao);
            stmt.setString(3, "Pendente");
            stmt.setInt(4, 1);
            stmt.setString(5, "Média");
            stmt.setDate(6, prazoSQL);

            stmt.executeUpdate();
        }

        carregarTarefasDoBanco();

        txtData.setText("");
        txtTitulo.setText("");
        txtDescricao.setText("");

        modoEdicao = false;
        linhaEdicao = -1;

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Tarefa salva no banco de dados com sucesso!"
        );

    } catch (java.sql.SQLException | NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao salvar tarefa: " + e.getMessage(),
                "Erro",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linhaSelecionada = tblCalendario.getSelectedRow();

    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecione uma tarefa para editar."
        );
        return;
    }

    // A tabela possui ID oculto na coluna 0.
    txtData.setText(
            tblCalendario.getValueAt(linhaSelecionada, 1).toString()
    );

    txtTitulo.setText(
            tblCalendario.getValueAt(linhaSelecionada, 2).toString()
    );

    Object descricao = tblCalendario.getValueAt(linhaSelecionada, 3);

    txtDescricao.setText(
            descricao == null ? "" : descricao.toString()
    );

    modoEdicao = true;
    linhaEdicao = linhaSelecionada;

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Altere os dados e clique em Adicionar para salvar."
    );

    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirCalendarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirCalendarioActionPerformed
       int linhaSelecionada = tblCalendario.getSelectedRow();

    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecione uma tarefa para excluir."
        );
        return;
    }

    int resposta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir esta tarefa?",
            "Confirmar exclusão",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (resposta != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    int linhaModelo = tblCalendario.convertRowIndexToModel(
            linhaSelecionada
    );

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblCalendario.getModel();

    int idTarefa = Integer.parseInt(
            modelo.getValueAt(linhaModelo, 0).toString()
    );

    String sql = "DELETE FROM tarefas WHERE id_tarefa = ?";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql)
    ) {
        stmt.setInt(1, idTarefa);

        int linhasAfetadas = stmt.executeUpdate();

        if (linhasAfetadas > 0) {
            carregarTarefasDoBanco();

            modoEdicao = false;
            linhaEdicao = -1;

            txtData.setText("");
            txtTitulo.setText("");
            txtDescricao.setText("");

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Tarefa excluída do banco de dados com sucesso!"
            );

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "A tarefa não foi encontrada no banco de dados."
            );
        }

    } catch (java.sql.SQLException | NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao excluir tarefa: " + e.getMessage(),
                "Erro",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnExcluirCalendarioActionPerformed

