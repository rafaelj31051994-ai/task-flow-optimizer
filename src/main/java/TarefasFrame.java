if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Selecione uma tarefa para excluir."
    );
    return;
}

int resposta = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Deseja realmente excluir esta tarefa?",
    "Confirmar exclusão",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (resposta != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

// Converte o índice da tabela para o índice do modelo.
int linhaModelo = tblTarefas.convertRowIndexToModel(linhaSelecionada);

javax.swing.table.DefaultTableModel modelo =
    (javax.swing.table.DefaultTableModel) tblTarefas.getModel();

// Obtém o ID da coluna oculta (índice 0).
int idTarefa = ((Number) modelo.getValueAt(
    linhaModelo, 0
)).intValue();

int idUsuario = SessaoUsuario.getIdUsuario();

if (idUsuario <= 0) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Não foi possível identificar o usuário conectado."
    );
    return;
}

java.sql.Connection conexao = null;
java.sql.PreparedStatement stmt = null;

try {
    conexao = Conexao.conectar();

    if (conexao == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Não foi possível conectar ao banco de dados."
        );
        return;
    }

    String sql =
        "DELETE FROM tarefas WHERE id_tarefa = ? AND id_usuario = ?";

    stmt = conexao.prepareStatement(sql);
    stmt.setInt(1, idTarefa);
    stmt.setInt(2, idUsuario);

    int linhasAfetadas = stmt.executeUpdate();

    if (linhasAfetadas == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "A tarefa não foi encontrada para este usuário."
        );
        return;
    }

    // Remove somente a linha correspondente no modelo.
    modelo.removeRow(linhaModelo);

    modoEdicao = false;
    linhaEdicao = -1;

    txtTitulo.setText("");
    txtDescricao.setText("");
    txtPrazo.setText("");
    cmbPrioridade.setSelectedIndex(0);
    cmbStatus.setSelectedIndex(0);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Tarefa excluída com sucesso!"
    );

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Erro ao excluir tarefa do banco de dados: "
        + e.getMessage()
    );

} finally {
    try {
        if (stmt != null) stmt.close();
        if (conexao != null) conexao.close();
    } catch (java.sql.SQLException e) {
        System.out.println(
            "Erro ao fechar conexão: " + e.getMessage()
        );
    }
}
