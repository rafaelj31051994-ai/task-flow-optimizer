    private void carregarTarefasDoBanco() {

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) tblTarefas.getModel();

    modelo.setRowCount(0);

    int idUsuario = SessaoUsuario.getIdUsuario();

    if (idUsuario <= 0) {
        return;
    }

    String sql = "SELECT id_tarefa, titulo, prioridade, prazo, status "
               + "FROM tarefas "
               + "WHERE id_usuario = ? "
               + "ORDER BY id_tarefa";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql)
    ) {

        stmt.setInt(1, idUsuario);

        try (java.sql.ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {

                int idTarefa = rs.getInt("id_tarefa");
                String titulo = rs.getString("titulo");
                String prioridade = rs.getString("prioridade");

                java.sql.Date prazoBanco = rs.getDate("prazo");

                String prazo = prazoBanco == null
                    ? ""
                    : new java.text.SimpleDateFormat("dd/MM/yyyy")
                        .format(prazoBanco);

                String status = rs.getString("status");

                modelo.addRow(new Object[]{
                    idTarefa,
                    titulo,
                    prioridade,
                    prazo,
                    status
                });
            }
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar as tarefas: " + e.getMessage(),
            "Erro",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
