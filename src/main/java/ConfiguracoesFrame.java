    private void carregarConfiguracoesDoBanco() {

    String sqlUsuario =
        "SELECT nome, email FROM usuarios WHERE id_usuario = ?";

    String sqlConfiguracao =
        "SELECT tema FROM configuracoes WHERE id_usuario = ?";

    try (java.sql.Connection conn = Conexao.conectar()) {

        try (java.sql.PreparedStatement stmt =
                 conn.prepareStatement(sqlUsuario)) {

            stmt.setInt(1, idUsuario);

            try (java.sql.ResultSet rs = stmt.executeQuery()) {

                if (rs.next()) {
                    txtNome.setText(rs.getString("nome"));
                    txtEmail.setText(rs.getString("email"));
                }
            }
        }

        try (java.sql.PreparedStatement stmt =
                 conn.prepareStatement(sqlConfiguracao)) {

            stmt.setInt(1, idUsuario);

            try (java.sql.ResultSet rs = stmt.executeQuery()) {

                if (rs.next()) {
                    cmbTema.setSelectedItem(rs.getString("tema"));
                } else {
                    cmbTema.setSelectedItem("Claro");
                }
            }
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar configurações: " + e.getMessage(),
            "Erro",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}

