    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        String nome = txtNome.getText().trim();
String email = txtEmail.getText().trim();
String cargo = cmbCargo.getSelectedItem().toString().trim();

if (nome.isEmpty() || email.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Preencha o nome e o e-mail."
    );
    return;
}

if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Informe um e-mail válido."
    );
    return;
}

if (modoEdicao) {
    String sql = "UPDATE usuarios SET nome = ?, email = ?, cargo = ? "
               + "WHERE id_usuario = ?";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql)
    ) {
        stmt.setString(1, nome);
        stmt.setString(2, email);
        stmt.setString(3, cargo);
        stmt.setInt(4, idUsuarioEdicao);

        int linhas = stmt.executeUpdate();

        if (linhas > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Membro atualizado com sucesso!"
            );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Nenhum usuário foi atualizado."
            );
        }

        modoEdicao = false;
        linhaEdicao = -1;
        idUsuarioEdicao = -1;

        txtNome.setText("");
        txtEmail.setText("");
        cmbCargo.setSelectedIndex(0);
        carregarUsuariosDoBanco();

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao atualizar membro: " + e.getMessage(),
            "Erro de banco de dados",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    return;
}

String sql = "INSERT INTO usuarios (nome, email, senha, cargo) "
           + "VALUES (?, ?, ?, ?)";

try (
    java.sql.Connection conn = Conexao.conectar();
    java.sql.PreparedStatement stmt = conn.prepareStatement(sql)
) {
    stmt.setString(1, nome);
    stmt.setString(2, email);
    stmt.setString(
        3, java.util.UUID.randomUUID().toString()
    );
    stmt.setString(4, cargo);

    stmt.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Membro cadastrado no banco com sucesso!"
    );

    txtNome.setText("");
    txtEmail.setText("");
    cmbCargo.setSelectedIndex(0);
    carregarUsuariosDoBanco();

} catch (java.sql.SQLIntegrityConstraintViolationException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Este e-mail já está cadastrado."
    );
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Erro ao cadastrar membro: " + e.getMessage(),
        "Erro de banco de dados",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linhaSelecionada = tblEquipe.getSelectedRow();

if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Selecione um membro para editar."
    );
    return;
}

// A coluna 0 do modelo contém o ID, mesmo estando oculta.
idUsuarioEdicao = Integer.parseInt(
    tblEquipe.getModel()
             .getValueAt(linhaSelecionada, 0)
             .toString()
);

txtNome.setText(
    tblEquipe.getModel().getValueAt(linhaSelecionada, 1).toString()
);

txtEmail.setText(
    tblEquipe.getModel().getValueAt(linhaSelecionada, 2).toString()
);

cmbCargo.setSelectedItem(
    tblEquipe.getModel().getValueAt(linhaSelecionada, 3).toString()
);

modoEdicao = true;

javax.swing.JOptionPane.showMessageDialog(
    this,
    "Altere os dados e clique em Adicionar para salvar."
);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linhaSelecionada = tblEquipe.getSelectedRow();

    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione um membro para excluir."
        );
        return;
    }

    int resposta = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Deseja realmente excluir este membro?",
        "Confirmar exclusão",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (resposta != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    // Obtém o ID da primeira coluna do modelo, que está oculta na tela.
    int idUsuario = Integer.parseInt(
        tblEquipe.getModel()
                .getValueAt(linhaSelecionada, 0)
                .toString()
    );

    String sql = "DELETE FROM usuarios WHERE id_usuario = ?";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql)
    ) {
        stmt.setInt(1, idUsuario);

        int linhasAfetadas = stmt.executeUpdate();

        if (linhasAfetadas > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Membro excluído com sucesso!"
            );

            txtNome.setText("");
            txtEmail.setText("");
            cmbCargo.setSelectedIndex(0);

            modoEdicao = false;
            linhaEdicao = -1;
            idUsuarioEdicao = -1;

            carregarUsuariosDoBanco();

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Nenhum membro foi encontrado para exclusão."
            );
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Erro ao excluir membro: " + e.getMessage(),
            "Erro de banco de dados",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnExcluirActionPerformed

