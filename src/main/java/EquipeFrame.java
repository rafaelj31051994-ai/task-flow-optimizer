    private void carregarUsuariosDoBanco() {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblEquipe.getModel();

    modelo.setRowCount(0);
    if (tblEquipe.getColumnModel().getColumnCount() == 4) {
    tblEquipe.getColumnModel().getColumn(0).setMinWidth(0);
    tblEquipe.getColumnModel().getColumn(0).setMaxWidth(0);
    tblEquipe.getColumnModel().getColumn(0).setPreferredWidth(0);
}

    String sql = "SELECT id_usuario, nome, email, cargo FROM usuarios";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
        java.sql.ResultSet rs = stmt.executeQuery()
    ) {
        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_usuario"),
                rs.getString("nome"),
                rs.getString("email"),
                rs.getString("cargo")
            });
        }
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar usuários: " + e.getMessage(),
                "Erro de banco de dados",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
