private void carregarDadosDashboard() {
    String sqlContagem =
            "SELECT " +
            "COUNT(*) AS total, " +
            "SUM(CASE WHEN status = 'Em andamento' THEN 1 ELSE 0 END) AS andamento, " +
            "SUM(CASE WHEN status IN ('Concluída', 'Concluído') THEN 1 ELSE 0 END) AS concluidas, " +
            "SUM(CASE WHEN status IN ('Pendente', 'Em andamento') " +
            "AND prazo < CURDATE() THEN 1 ELSE 0 END) AS atrasadas " +
            "FROM tarefas";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conn.prepareStatement(sqlContagem);
        java.sql.ResultSet rs = stmt.executeQuery()
    ) {
        if (rs.next()) {
            IbITotalTarefas.setText(
                    "Total de tarefas: " + rs.getInt("total")
            );

            IbIEmAndamento.setText(
                    "Em andamento: " + rs.getInt("andamento")
            );

            IbIConcluidas.setText(
                    "Concluídas: " + rs.getInt("concluidas")
            );

            IbIAtrasadas.setText(
                    "Atrasadas: " + rs.getInt("atrasadas")
            );
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar os indicadores do Dashboard: "
                        + e.getMessage(),
                "Erro de banco de dados",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    carregarTarefasRecentes();
}
private void carregarTarefasRecentes() {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel)
                    tblTarefas.getModel();

    modelo.setRowCount(0);

    String sql =
            "SELECT titulo, prioridade, prazo, status " +
            "FROM tarefas " +
            "ORDER BY id_tarefa DESC " +
            "LIMIT 5";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt =
                conn.prepareStatement(sql);
        java.sql.ResultSet rs = stmt.executeQuery()
    ) {
        while (rs.next()) {
            java.sql.Date prazoBanco = rs.getDate("prazo");

            String prazo = prazoBanco == null
                    ? ""
                    : new java.text.SimpleDateFormat("dd/MM/yyyy")
                            .format(prazoBanco);

            modelo.addRow(new Object[]{
                rs.getString("titulo"),
                rs.getString("prioridade"),
                prazo,
                rs.getString("status")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar tarefas recentes: "
                        + e.getMessage(),
                "Erro de banco de dados",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
