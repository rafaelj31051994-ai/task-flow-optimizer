private void carregarRelatorioDoBanco() {
    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblRelatorio.getModel();

    modelo.setRowCount(0);

    int total = 0;
    int concluidas = 0;
    int andamento = 0;
    int atrasadas = 0;

    String sql = "SELECT titulo, prioridade, prazo, status FROM tarefas";

    try (
        java.sql.Connection conn = Conexao.conectar();
        java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
        java.sql.ResultSet rs = stmt.executeQuery()
    ) {
        java.util.Date dataAtual = new java.util.Date();

        while (rs.next()) {
            String titulo = rs.getString("titulo");
            String prioridade = rs.getString("prioridade");
            java.sql.Date prazoBanco = rs.getDate("prazo");
            String status = rs.getString("status");

            String prazo = prazoBanco == null
                    ? ""
                    : new java.text.SimpleDateFormat("dd/MM/yyyy")
                            .format(prazoBanco);

            modelo.addRow(new Object[]{
                titulo,
                prioridade,
                prazo,
                status
            });

            total++;

            if ("Concluída".equalsIgnoreCase(status)
                    || "Concluído".equalsIgnoreCase(status)) {
                concluidas++;
            }

            if ("Em andamento".equalsIgnoreCase(status)) {
                andamento++;
            }

            if (prazoBanco != null
                    && prazoBanco.before(dataAtual)
                    && !"Concluída".equalsIgnoreCase(status)
                    && !"Concluído".equalsIgnoreCase(status)) {
                atrasadas++;
            }
        }

        IbINumeroTotal.setText(String.valueOf(total));
        IbINumeroConcluidas.setText(String.valueOf(concluidas));
        IbINumeroAndamento.setText(String.valueOf(andamento));
        IbINumeroAtrasadas.setText(String.valueOf(atrasadas));

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar o relatório: " + e.getMessage(),
                "Erro de banco de dados",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
