    private void bntEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntEntrarActionPerformed
       String email = txtEmail.getText().trim();
String senha = txtSenha.getText();

if (email.isEmpty() || senha.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Preencha o e-mail e a senha.");
    return;
}

String sql = "SELECT * FROM usuarios WHERE email = ? AND senha = ?";

try (
    java.sql.Connection conexao = Conexao.conectar();
    java.sql.PreparedStatement stmt = conexao.prepareStatement(sql)
) {

    stmt.setString(1, email);
    stmt.setString(2, senha);

    java.sql.ResultSet resultado = stmt.executeQuery();

    if (resultado.next()) {

    int id = resultado.getInt("id_usuario");
    String nome = resultado.getString("nome");
    String emailUsuario = resultado.getString("email");

    SessaoUsuario.iniciarSessao(id, nome, emailUsuario);

    JOptionPane.showMessageDialog(
            this,
            "Login realizado com sucesso!"
    );

    DashboardFrame dashboard = new DashboardFrame(id);
dashboard.setVisible(true);
this.dispose();

} else {
    JOptionPane.showMessageDialog(
            this,
            "E-mail ou senha incorretos."
    );
    }
} catch (java.sql.SQLException e) {

    JOptionPane.showMessageDialog(this,
            "Erro ao acessar o banco de dados: " + e.getMessage());

}


    }//GEN-LAST:event_bntEntrarActionPerformed

